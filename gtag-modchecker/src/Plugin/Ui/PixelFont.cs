        /// <summary>Legger til firkanter for alle '#'/symbol-piksler i en bitmap. (x0,y0) = øverste venstre hjørne, px = pikselstørrelse.</summary>
        public static void AddBitmap(List<Vector3> v, List<int> tris, string[] rows, char symbol, float x0, float y0, float px)
        {
            for (int r = 0; r < rows.Length; r++)
            {
                string row = rows[r];
                int c = 0;
                while (c < row.Length)
                {
                    if (row[c] != symbol) { c++; continue; }
                    int s = c;
                    while (c < row.Length && row[c] == symbol) c++;
                    AddQuad(v, tris, x0 + s * px, y0 - r * px, x0 + c * px, y0 - (r + 1) * px);
                }
            }
        }

        public static void AddGlyph(List<Vector3> v, List<int> tris, byte[] g, float x0, float y0, float px)
        {
            for (int r = 0; r < 8; r++)
            {
                int bits = g[r];
                int c = 0;
                while (c < 8)
                {
                    if ((bits & (0x80 >> c)) == 0) { c++; continue; }
                    int s = c;
                    while (c < 8 && (bits & (0x80 >> c)) != 0) c++;
                    AddQuad(v, tris, x0 + s * px, y0 - r * px, x0 + c * px, y0 - (r + 1) * px);
                }
            }
        }

        /// <summary>Firkant synlig forfra (samme vinding som UiKit sin quad).</summary>
        public static void AddQuad(List<Vector3> v, List<int> tris, float xa, float ya, float xb, float yb)
        {
            int i = v.Count;
            float l = Mathf.Min(xa, xb), r = Mathf.Max(xa, xb), b = Mathf.Min(ya, yb), t = Mathf.Max(ya, yb);
            v.Add(new Vector3(l, b, 0)); v.Add(new Vector3(r, b, 0)); v.Add(new Vector3(l, t, 0)); v.Add(new Vector3(r, t, 0));
            tris.Add(i); tris.Add(i + 2); tris.Add(i + 1);
            tris.Add(i + 2); tris.Add(i + 3); tris.Add(i + 1);
        }
