        private static Dictionary<char, byte[]> _glyphs;

        public static byte[] Glyph(char c)
        {
            if (_glyphs == null) Load();
            if (_glyphs.TryGetValue(c, out var g)) return g;
            // Aksenter vi ikke har: prøv uten aksent (é -> e), ellers '?'
            string d = c.ToString().Normalize(NormalizationForm.FormD);
            foreach (char ch in d)
                if (CharUnicodeInfo.GetUnicodeCategory(ch) != UnicodeCategory.NonSpacingMark && _glyphs.TryGetValue(ch, out g)) return g;
            if (c == '\u2026') return _glyphs['.'];
            if (c == '\u00B7' || c == '\u2022') return _glyphs['\u00B7'];
            if (c == '\u2013' || c == '\u2014') return _glyphs['-'];
            if (c == '\u2018' || c == '\u2019') return _glyphs['\''];
            if (c == '\u201C' || c == '\u201D') return _glyphs['"'];
            return _glyphs['?'];
        }

        private static void Load()
        {
            _glyphs = new Dictionary<char, byte[]>();
            for (int i = 0; i < Chars.Length; i++)
            {
                var b = new byte[8];
                for (int r = 0; r < 8; r++) b[r] = Convert.ToByte(Data.Substring(i * 16 + r * 2, 2), 16);
                _glyphs[Chars[i]] = b;
            }
        }

