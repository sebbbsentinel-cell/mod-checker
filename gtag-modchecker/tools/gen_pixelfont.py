# Lager src/Plugin/Ui/PixelFontData.cs: 8x8 bitmaps (rad for rad, bit 7 = venstre kolonne)
# avledet fra Press Start 2P (SIL OFL 1.1). Det avledede bitmap-fontet heter "SebPixel" fordi
# "Press Start 2P" er et reservert fontnavn i OFL-lisensen.
from PIL import Image, ImageDraw, ImageFont
import sys
TTF = '/usr/share/fonts/truetype/sand-box/google/Press Start 2P/PressStart2P-Regular.ttf'
f = ImageFont.truetype(TTF, 8)
chars = [chr(c) for c in list(range(32, 127)) + list(range(0xA1, 0x100)) if c != 0xAD]
hexes = []
for ch in chars:
    im = Image.new('L', (14, 14), 0); ImageDraw.Draw(im).text((3, 3), ch, font=f, fill=255)
    rows = []
    for y in range(3, 11):
        v = 0
        for x in range(3, 11):
            if im.getpixel((x, y)) > 127: v |= 1 << (7 - (x - 3))
        rows.append(v)
    hexes.append(''.join('%02X' % r for r in rows))
cs_chars = ''.join(chars).replace('\\', '\\\\').replace('"', '\\"')
out = []
out.append('// <auto-generated> tools/gen_pixelfont.py </auto-generated>')
out.append('// "SebPixel" 8x8 bitmap font. Glyph bitmaps derived from Press Start 2P,')
out.append('// Copyright 2012 The Press Start 2P Project Authors (cody@zone38.net), SIL Open Font License 1.1 (see LICENSE-OFL.txt).')
out.append('namespace GTagModChecker')
out.append('{')
out.append('    internal static partial class PixelFont')
out.append('    {')
out.append('        internal const string Chars = "%s";' % cs_chars)
out.append('        internal const string Data =')
for i in range(0, len(hexes), 8):
    out.append('            "%s"%s' % (''.join(hexes[i:i+8]), ' +' if i + 8 < len(hexes) else ';'))
out.append('    }')
out.append('}')
open(sys.argv[1], 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(len(chars), 'glyphs')
